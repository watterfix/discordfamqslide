class Help(commands.Cog):
    def embed(self, guild):
        e = make(f"📖 {FAMILY} · все команды", "Команды начинаются с `/`.\n🔒 — только для руководства.", COLOR["main"])
        if guild.icon: e.set_thumbnail(url=guild.icon.url)
        for name, val in SECTIONS:
            e.add_field(name=name, value=val, inline=False)
        return e

    @app_commands.command(name="помощь", description="Список всех команд бота")
    async def help(self, i):
        await i.response.send_message(embed=self.embed(i.guild), ephemeral=True)

async def setup(bot): await bot.add_cog(Help())
